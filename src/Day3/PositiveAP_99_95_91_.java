package Day3;

public class PositiveAP_99_95_91_ {
    static void main(){
        System.out.print("Print positive portion of Arithmetic Progression,\n 99, 95, 91,.....\n\nPrinting the complete series,     ");
        int x=99;
        while(x>=0){
            System.out.print(x+ " ");
            x-=4;
        }
    }
}
